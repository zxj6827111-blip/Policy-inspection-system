class TestOcr:
    def test_tesseract_available_or_skips_gracefully(self):
        from app.ocr import ocr_pdf, tesseract_available
        payload = _make_scanned_pdf_no_text()
        result = ocr_pdf(payload)
        if tesseract_available():
            # OCR may succeed or fail depending on the blank page; both are acceptable.
            assert result.status in ("ok", "failed")
        else:
            assert result.status == "failed"
            assert "tesseract_not_installed" in result.error

    def test_ocr_failure_does_not_auto_flag(self, tmp_path: Path):
        """OCR failure must not produce findings (V3.0 §9.5)."""
        db = _setup_db(tmp_path)
        doc_id = _seed_document(db)
        from app.pdf_service import process_document_pdf
        # Use blank PDF with OCR disabled to simulate OCR not running
        payload = _make_scanned_pdf_no_text()
        result = process_document_pdf(
            db, document_id=doc_id, pdf_payload=payload,
            body_text="正文", run_ocr=False, run_compare=False,
        )
        # No findings should be auto-emitted from OCR absence
        assert "PDF-001" not in result.rule_codes  # not corrupted
        assert "PDF-002" not in result.rule_codes  # not encrypted
        # PDF-003 (blank) may be emitted since integrity check is independent of OCR
        # but OCR-related findings should not be emitted.
        with db.connect() as conn:
            ocr_findings = conn.execute(
                "SELECT COUNT(*) FROM rule_findings WHERE rule_code LIKE 'OCR%'"
            ).fetchone()[0]
        assert ocr_findings == 0


