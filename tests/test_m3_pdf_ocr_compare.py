def _make_simple_pdf(title: str = "测试政策文件", body_lines: list[str] | None = None) -> bytes:
    """Generate a minimal valid PDF with text layer using pypdf."""
    from pypdf import PdfWriter
    from pypdf.generic import RectangleObject

    writer = PdfWriter()
    # Add a blank page and append text content via a content stream.
    # pypdf does not support high-level text drawing, so we use page.merge_page
    # with a generated content stream. Easier: use reportlab if available;
    # if not, fall back to pypdf's low-level page content.
    page = writer.add_blank_page(width=595, height=842)
    text_lines = [title] + (body_lines or [
        "上海市普陀区人民政府",
        "普府〔2024〕10号",
        "2024年3月15日",
    ])
    content = "BT\n/F1 12 Tf\n50 800 Td\n"
    for i, line in enumerate(text_lines):
        # Escape parentheses in text
        safe = line.replace("(", r"\(").replace(")", r"\)")
        content += f"({safe}) Tj\n0 -18 Td\n"
    content += "ET\n"
    page.compress_content_streams()
    # Use low-level approach: set /Contents directly
    from pypdf.generic import ContentStream, DecodedStreamObject, NameObject, ArrayObject, DictionaryObject
    # Easier path: just write text via a content stream
    stream = DecodedStreamObject()
    stream.set_data(content.encode("latin-1", errors="replace"))
    page[NameObject("/Contents")] = writer._add_object(stream)
    # Add a minimal font resource so the content stream can reference /F1
    from pypdf.generic import TextStringObject, NumberObject
    font_dict = DictionaryObject()
    font_dict[NameObject("/Type")] = NameObject("/Font")
    font_dict[NameObject("/Subtype")] = NameObject("/Type1")
    font_dict[NameObject("/BaseFont")] = NameObject("/Helvetica")
    font_ref = writer._add_object(font_dict)
    resources = DictionaryObject()
    fonts = DictionaryObject()
    fonts[NameObject("/F1")] = font_ref
    resources[NameObject("/Font")] = fonts
    page[NameObject("/Resources")] = resources

    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


def _make_corrupted_pdf() -> bytes:
    """Return bytes that look like a PDF but are truncated/corrupted."""
    return b"%PDF-1.4\nbroken content\n%%EOF"


def _make_encrypted_pdf() -> bytes:
    """Generate a minimal encrypted PDF with a non-empty user password.

    pypdf's `decrypt("")` must fail for this PDF to be detected as encrypted.
    """
    from pypdf import PdfWriter
    writer = PdfWriter()
    writer.add_blank_page(width=595, height=842)
    # Use a non-empty user password so empty-password decrypt fails.
    writer.encrypt(user_password="secret_user_pw", owner_password="secret_owner")
    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


def _make_scanned_pdf_no_text() -> bytes:
    """Generate a blank PDF with no text layer (simulating a scanned PDF)."""
    from pypdf import PdfWriter
    writer = PdfWriter()
    writer.add_blank_page(width=595, height=842)
    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


